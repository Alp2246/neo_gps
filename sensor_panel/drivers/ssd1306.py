# SSD1306 baslatma komut dizisi (128x64)
INIT_SEQ = (
    0xAE,        # display off
    0xD5, 0x80,  # clock div
    0xA8, 0x3F,  # multiplex 1/64
    0xD3, 0x00,  # display offset 0
    0x40,        # start line 0
    0x8D, 0x14,  # charge pump on
    0x20, 0x00,  # memory mode = horizontal
    0xA1,        # segment remap
    0xC8,        # COM scan dec
    0xDA, 0x12,  # COM pins
    0x81, 0xCF,  # contrast
    0xD9, 0xF1,  # precharge
    0xDB, 0x40,  # vcom detect
    0xA4,        # resume to RAM content
    0xA6,        # normal (not inverted)
    0xAF,        # display on
)


class SSD1306:
    def __init__(self, i2c, addr=0x3C, width=WIDTH, height=HEIGHT):
        self.i2c = i2c
        self.addr = addr
        self.width = width
        self.height = height
        self.pages = height // 8
        self.buf = bytearray(width * self.pages)
        self.init_display()

    def _cmd(self, *cmds):
        # Her komutu CTRL_CMD ile gonder (basit ve guvenli)
        for c in cmds:
            self.i2c.write(self.addr, [CTRL_CMD, c])

    def init_display(self):
        for c in INIT_SEQ:
            self.i2c.write(self.addr, [CTRL_CMD, c])
        self.clear()
        self.show()

    def clear(self):
        for i in range(len(self.buf)):
            self.buf[i] = 0x00

    def pixel(self, x, y, on=1):
        if 0 <= x < self.width and 0 <= y < self.height:
            page = y // 8
            bit = 1 << (y & 7)
            idx = x + page * self.width
            if on:
                self.buf[idx] |= bit
            else:
                self.buf[idx] &= ~bit

    def text(self, s, x, y, on=1):
        """5x7 font ile yazi. x,y sol-ust kose (piksel)."""
        cx = x
        for ch in s:
            glyph = FONT.get(ch, FONT.get('?'))
            for col in range(5):
                bits = glyph[col]
                for row in range(7):
                    if bits & (1 << row):
                        self.pixel(cx + col, y + row, on)
            cx += 6
            if cx >= self.width:
                break

    def hline(self, x, y, w, on=1):
        for i in range(w):
            self.pixel(x + i, y, on)

    def show(self):
        """Framebuffer'i ekrana yaz."""
        self._cmd(0x21, 0, self.width - 1)        # column 0..127
        self._cmd(0x22, 0, self.pages - 1)        # page 0..7
        # Veriyi parcalar halinde gonder (her transaction CTRL_DATA + N bayt)
        chunk = 32
        for i in range(0, len(self.buf), chunk):
            self.i2c.write(self.addr, [CTRL_DATA] + list(self.buf[i:i + chunk]))

    def contrast(self, value):
        self._cmd(0x81, value & 0xFF)

    def invert(self, on):
        self._cmd(0xA7 if on else 0xA6)


def main():
    from axi_gpio_i2c import AxiGpioI2C
    i2c = AxiGpioI2C(base=0x41200000)
    try:
        found = i2c.scan()
        print("I2C cihazlar:", [hex(a) for a in found])
        addr = 0x3C if 0x3C in found else (0x3D if 0x3D in found else 0x3C)
        print(f"OLED adres: 0x{addr:02X}")
        oled = SSD1306(i2c, addr=addr)
        oled.clear()
        oled.text("PYNQ-Z2", 0, 0)
        oled.text("SSD1306 OLED", 0, 12)
        oled.text("I2C bit-bang", 0, 24)
        oled.text("0x%02X @ AXI GPIO" % addr, 0, 36)
        oled.hline(0, 46, 128)
        oled.text("GPS hazir...", 0, 52)
        oled.show()
        print("[OK] Ekrana test yazisi basildi.")
    finally:
        i2c.close()


if __name__ == "__main__":
    main()
